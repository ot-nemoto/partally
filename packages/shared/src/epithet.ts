export const EPITHET_MAX_LENGTH = 20;

/** 0 以上 max 未満の整数を返す乱数関数。テストで差し替えられるようにする */
export type RandomInt = (max: number) => number;

export function randomEpithet(randomInt: RandomInt): string {
  const prefix = EPITHET_PREFIXES[randomInt(EPITHET_PREFIXES.length)];
  const title = EPITHET_TITLES[randomInt(EPITHET_TITLES.length)];
  return `${prefix}${title}`;
}

export function formatDisplayName(epithet: string, name: string): string {
  return `〈${epithet}〉${name}`;
}
